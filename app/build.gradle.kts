fun gitTagVersionName(): String {
    return try {
        val proc = ProcessBuilder("git", "describe", "--tags", "--always")
            .directory(rootProject.projectDir)
            .redirectErrorStream(true)
            .start()
        val out = proc.inputStream.bufferedReader().readText().trim()
        if (proc.waitFor() == 0 && out.isNotBlank()) out.removePrefix("v") else "0.1.0"
    } catch (_: Exception) {
        "0.1.0"
    }
}

val keystoreProperties = Properties().apply {
    val candidates = listOf(
        rootProject.file("keystore.properties"),
        file("${System.getProperty("user.home")}/.euterpe/keystore.properties"),
    )
    candidates.firstOrNull { it.exists() }?.inputStream()?.use { load(it) }
}

fun signingValue(envName: String, propName: String): String? =
    System.getenv(envName)?.takeIf { it.isNotBlank() }
        ?: keystoreProperties.getProperty(propName)?.takeIf { it.isNotBlank() }

